package StringsBasics;

public class LowerCaseUpperCaseFunction {
    public static void main(String[] args) {
        String str = "ADITYA PATIL";
        System.out.println(str.toLowerCase());
        // converts all words to lower case letters [Non capital]

        String str1 = "Aditya Patil";
        System.out.println(str1.toUpperCase());
        //converts all words to upper case letters [only capital]
    }
}
