package BasicsofJava;

public class variablesint {
    public static void main(String[] args){
       int x; // declarartion of variable
        x = 5 ; // intialization of the variable with integer value 5
        System.out.println(x); // printing the variable

        x = 500; // updating the variable value
        System.out.println(x); // printing the updated value

        // we can also do arithemetic operations with this variable

        System.out.println(x + 5);

        // here our x updated value is  500 and
       // x + 5 = 505 will be printed
    }
}
