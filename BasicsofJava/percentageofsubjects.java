package BasicsofJava;

public class percentageofsubjects {
    public static void main(String[] args) {
        double mathmarks = 95; // maths marks
        double engmarks = 96; // english marks
        double phymarks = 85; // physics marks
        double chemmarks = 88; // chemistry marks
        double econmicsarks = 82; // econmics marks
        double p = (mathmarks + engmarks + phymarks +
                chemmarks + econmicsarks )/ 5;
        System.out.println(p);
    }
}
